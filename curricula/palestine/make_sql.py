"""Turns the all-grades spreadsheet into import.sql for the live database.

The SQL only adds what is missing (matched by name), fills lesson content only
where it is still empty, makes the Palestinian curriculum available and
publishes its subjects. Running it twice changes nothing.

    python3 curricula/palestine/make_sql.py
"""
import pathlib
import openpyxl

HERE = pathlib.Path(__file__).parent
SRC = HERE / "xlsx" / "منهاج-فلسطين-كل-الصفوف.xlsx"
OUT = HERE / "import.sql"
CONTENT_DIR = HERE / "import-content"  # lesson text, split so each request stays small
CHUNK = 1_000_000

GRADE_ORDER = ["الأول", "الثاني", "الثالث", "الرابع", "الخامس", "السادس", "السابع",
               "الثامن", "التاسع", "العاشر", "الحادي عشر", "الثاني عشر"]
STREAMS = ["علمي", "أدبي", "صناعي", "ريادي"]


def grade_info(name):
    base, _, stream = name.removeprefix("الصف ").partition(" - ")
    n = GRADE_ORDER.index(base) + 1
    stage = "elementary" if n <= 4 else "middle" if n <= 9 else "secondary"
    order = n * 10 + (STREAMS.index(stream) if stream else 0)
    return order, stage


def q(v):
    return "null" if v is None or str(v).strip() == "" else "'" + str(v).strip().replace("'", "''") + "'"


rows = list(openpyxl.load_workbook(SRC, read_only=True).active.iter_rows(values_only=True))[1:]
orders = {}  # running sort order for subjects/units/lessons/outcomes, by parent
values = []
contents = []
for grade, subject, unit, lesson, outcome, content in rows:
    g_ord, stage = grade_info(grade)
    def order(key):
        if key not in orders:
            orders[key] = sum(1 for k in orders if k[:-1] == key[:-1])
        return orders[key]
    s_ord = order((grade, subject))
    u_ord = order((grade, subject, unit))
    l_ord = order((grade, subject, unit, lesson))
    o_ord = order((grade, subject, unit, lesson, outcome)) if outcome else 0
    values.append(f"({g_ord},{q(grade)},'{stage}',{s_ord},{q(subject)},{u_ord},{q(unit)},"
                  f"{l_ord},{q(lesson)},{o_ord},{q(outcome)},null)")
    if content:
        contents.append(f"({q(grade)},{q(subject)},{q(unit)},{q(lesson)},{q(content)})")

sql = f"""-- Generated by make_sql.py from {SRC.name}. Do not edit by hand.
begin;

create temp table imp (g_ord int, grade text, stage public.school_stage, s_ord int, subject text,
  u_ord int, unit text, l_ord int, lesson text, o_ord int, outcome text, content text) on commit drop;

insert into imp values
{",\n".join(values)};

insert into public.curricula (slug, name, country, currency_code, is_available, sort_order)
select 'palestinian', 'المنهاج الفلسطيني المعتمد', 'فلسطين', 'ILS', true, 1
where not exists (select 1 from public.curricula where slug = 'palestinian');
update public.curricula set is_available = true where slug = 'palestinian';

insert into public.grades (curriculum_id, name, stage, sort_order)
select distinct c.id, i.grade, i.stage, i.g_ord
from imp i cross join public.curricula c
where c.slug = 'palestinian'
  and not exists (select 1 from public.grades g where g.curriculum_id = c.id and g.name = i.grade);
"""
G = "join public.grades g on g.name = i.grade and g.curriculum_id = (select id from public.curricula where slug = 'palestinian')"
S = G + " join public.subjects s on s.grade_id = g.id and s.name = i.subject"
U = S + " join public.units u on u.subject_id = s.id and u.title = i.unit"
L = U + " join public.lessons l on l.unit_id = u.id and l.title = i.lesson"
sql += f"""
insert into public.subjects (grade_id, name, status, sort_order)
select distinct g.id, i.subject, 'published'::public.content_status, i.s_ord from imp i {G}
where not exists (select 1 from public.subjects s where s.grade_id = g.id and s.name = i.subject);

insert into public.units (subject_id, title, sort_order)
select distinct s.id, i.unit, i.u_ord from imp i {S}
where not exists (select 1 from public.units u where u.subject_id = s.id and u.title = i.unit);

insert into public.lessons (unit_id, title, sort_order)
select distinct u.id, i.lesson, i.l_ord from imp i {U}
where not exists (select 1 from public.lessons l where l.unit_id = u.id and l.title = i.lesson);

insert into public.learning_outcomes (lesson_id, text, sort_order)
select distinct l.id, i.outcome, i.o_ord from imp i {L}
where i.outcome is not null
  and not exists (select 1 from public.learning_outcomes o where o.lesson_id = l.id and o.text = i.outcome);

update public.subjects set status = 'published'
where grade_id in (select g.id from public.grades g
                   join public.curricula c on c.id = g.curriculum_id
                   where c.slug = 'palestinian' and g.name in (select grade from imp));

commit;

select (select count(*) from public.grades g join public.curricula c on c.id = g.curriculum_id where c.slug = 'palestinian') as grades,
       (select count(*) from public.subjects s join public.grades g on g.id = s.grade_id join public.curricula c on c.id = g.curriculum_id where c.slug = 'palestinian' and s.status = 'published') as published_subjects,
       (select count(*) from public.lessons l join public.units u on u.id = l.unit_id join public.subjects s on s.id = u.subject_id join public.grades g on g.id = s.grade_id join public.curricula c on c.id = g.curriculum_id where c.slug = 'palestinian') as lessons,
       (select count(*) from public.lessons l join public.units u on u.id = l.unit_id join public.subjects s on s.id = u.subject_id join public.grades g on g.id = s.grade_id join public.curricula c on c.id = g.curriculum_id where c.slug = 'palestinian' and coalesce(l.content, '') <> '') as lessons_with_content;
"""
OUT.write_text(sql, encoding="utf-8")
print(f"{OUT}: {len(values)} rows, {len(sql):,} chars")

# Lesson text: fills only lessons whose text is still empty.
for old in CONTENT_DIR.glob("*.sql"):
    old.unlink()
CONTENT_DIR.mkdir(exist_ok=True)
chunks, cur = [], []
for v in contents:
    if cur and sum(map(len, cur)) + len(v) > CHUNK:
        chunks.append(cur)
        cur = []
    cur.append(v)
if cur:
    chunks.append(cur)
for n, chunk in enumerate(chunks, 1):
    part = f"""-- Generated by make_sql.py. Do not edit by hand.
begin;
create temp table imp (grade text, subject text, unit text, lesson text, content text) on commit drop;
insert into imp values
{",\n".join(chunk)};
update public.lessons l set content = i.content
from imp i {G} join public.subjects s on s.grade_id = g.id and s.name = i.subject
  join public.units u on u.subject_id = s.id and u.title = i.unit
where l.unit_id = u.id and l.title = i.lesson and coalesce(l.content, '') = '';
commit;
select count(*) as lessons_with_content from public.lessons where coalesce(content, '') <> '';
"""
    (CONTENT_DIR / f"part{n:02d}.sql").write_text(part, encoding="utf-8")
print(f"{CONTENT_DIR}: {len(contents)} lessons in {len(chunks)} files")
